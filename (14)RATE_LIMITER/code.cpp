// ============ RATE LIMITER ABSTRACTIONS ======================
class IRate_limiter {
public:
    virtual Response* receive_request(Request* request) = 0;
    virtual ~IRate_limiter() {};
};

class Fixed_Window : public IRate_limiter {
private:
    static mutex mtx;
    // now to implement refreshment intervals , we need two things, creation time of this rate limiter, and window length
    long long creation_time;


    long long window_length; //milliseconds..
    int requests_allowed_per_window;
    map<string, int> request_count; //{user_id : requests made till now}
    map<string, long long> last_request_time; //{user_id : last request time in milliseconds made by this user}

public:
    Fixed_Window(long long window_length, int rpw) {
        this->window_length = window_length;
        this->requests_allowed_per_window = rpw;

        // assign creation time
        auto wall_now = chrono::system_clock::now();
        long long time_ms = chrono::duration_cast<chrono::milliseconds>(wall_now.time_since_epoch()).count();
        this->creation_time = time_ms;

    }

    Response* receive_request(Request* request) override {
        // step 1 : updates the request_count of this user if it is time to count = 0
        lock_guard<mutex> lock(Fixed_Window::mtx);
        long long req_time = request->get_req_time();
        string user_id = request->get_user_id();


        // get the last multiple of window length starting from creation time
        long long k = (req_time - this->creation_time)/this->window_length;
        long long multiple = this->creation_time + (k*this->window_length);


        // now see if the request by this user was made before this multiple or after this
        // if before this multiple was his/her last request, then reset his/her count to 0
        if (this->last_request_time.find(user_id) == this->last_request_time.end() || (req_time > multiple && this->last_request_time[user_id] < multiple)) {
            // means first request OR replenishment needed
            this->request_count[user_id] = 0;
        }

        // if after this multiple, means count was already set to 0 earlier, no need to reset to 0 now



        // step 2 : if request_count of current user_id < rpw, then the request is sent to server, else rejected
        if (this->request_count[user_id] < this->requests_allowed_per_window) {
            // we can send the request to server...

            this->request_count[user_id]++;
            

            // update latest request time
            this->last_request_time[user_id] = req_time;



            // for now we are just returning a draft success message, in real application the response returned from server would have been returned
            return new Response(200, "successful request...");
        }
        return new Response(429, "Too many requests...");
    }
};

mutex Fixed_Window::mtx;

class Token_Bucket : public IRate_limiter {
private:
    static mutex mtx;
    long long creation_time;
    map<string, int> tokens; // {user_id : tokens_remaining}
    map<string, long long> last_request_time; // {user_id : last_time_of request from this user_id}
    long long window_length;
    long long refill_rate;
    int requests_allowed_per_window;
public:
    Token_Bucket(long long window_length, int rpw) {
        this->window_length = window_length;
        this->requests_allowed_per_window = rpw;
        this->refill_rate = this->window_length/this->requests_allowed_per_window;
        // assign creation time
        auto wall_now = chrono::system_clock::now();
        long long time_ms = chrono::duration_cast<chrono::milliseconds>(wall_now.time_since_epoch()).count();
        this->creation_time = time_ms;
    }

    int calc_tokens(long long req_time, string user_id) {
        long long highest_multiple_less_than_req_time = (req_time - this->creation_time)/this->refill_rate;
        long long just_greater_multiple_than_last_request_time = ((this->last_request_time[user_id] - this->creation_time)/this->refill_rate) + 1;
        int gap = (int)(highest_multiple_less_than_req_time - just_greater_multiple_than_last_request_time) + 1;
        gap = max(0, gap);
        return gap;
    }

    Response* receive_request(Request* request) override {
        // step 1 : checks current time and see if it is time for replenishment of token for this user,
        // if yes, then it calculates how much tokens need to be replenished, according to current time and last replenished time for this user without exceeding limit

        // max(tokens) = rpw
        lock_guard<mutex> lock(Token_Bucket::mtx);
        long long req_time = request->get_req_time();
        string user_id = request->get_user_id();

        

        // t=creation_time----------t = ct + (1*rr)----------t = ct + (2*rr)--------t = ct + (3*rr)----------t = ct + (4*rr)

        if (this->last_request_time.find(user_id) == this->last_request_time.end()) {
            // means this is his/her first request
            this->tokens[user_id] = this->requests_allowed_per_window;
        } else if (this->last_request_time.find(user_id) != this->last_request_time.end()) {
            // now check the complete intervals of replenishment that lie between last_request_time and req_time
            int tokens_to_be_added = this->calc_tokens(req_time, user_id);
            this->tokens[user_id]+=tokens_to_be_added;
            this->tokens[user_id] = min(this->requests_allowed_per_window, this->tokens[user_id]);

        }

        // step 2 : if tokens are > 0, request is sent to user, and a success response is created and sent back
        // else, a code 429(too many requests) is sent back
        if (this->tokens[user_id] > 0) {

            // send request to server and reduce one token
            this->tokens[user_id]--;

            // update latest request time
            this->last_request_time[user_id] = req_time;
            // return draft response for now
            return new Response(200, "successful request...");


        }

        return new Response(429, "Too many requests");
    }
};
mutex Token_Bucket::mtx;
class Sliding_Window_Log : public IRate_limiter {
private:
    static mutex mtx;
    long long window_length;
    int requests_allowed_per_window;
    map<string, queue<long long>> successful_requests; //{user_id : queue of at most size rpw having times of successfull requests in milliseconds};
public:
    Sliding_Window_Log(long long window_length, int rpw) {
        this->window_length = window_length;
        this->requests_allowed_per_window = rpw;
    }

    Response* receive_request(Request* request) {
        // step 1 : update the queue for current user
        
        lock_guard<mutex> lock(Sliding_Window_Log::mtx);
        long long req_time = request->get_req_time();
        string user_id = request->get_user_id();

        // adjust queue first of this player
        if (this->successful_requests.find(user_id) == this->successful_requests.end()) {
            queue<long long> q;
            this->successful_requests[user_id] = q;

        }

        // update queue
        long long left_limit = max((long long)0, req_time - this->window_length);

        while (!this->successful_requests[user_id].empty() && this->successful_requests[user_id].front() < left_limit) {
            this->successful_requests[user_id].pop();
        }

        // step 2 : if size of queue of current user is < rpw, then request is sent to server and a success respone is returned, else a 492 is returned
        if (this->successful_requests[user_id].size() < this->requests_allowed_per_window) {
            // send request to server
            
            this->successful_requests[user_id].push(req_time);
            return new Response(200, "successful requests...");

        }
        return new Response(429, "Too many requests...");
    }
};

mutex Sliding_Window_Log::mtx;
