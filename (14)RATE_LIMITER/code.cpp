// ======================= Tier Map ============================
class Map {
private:
    map<Tier, IRate_limiter*> mp;
public:
    Map () {};
    ~Map() {
        for (auto&it : this->mp) {
            delete it.second;
        }
    }

    friend class Map_Builder;

    IRate_limiter* get_rate_limiter(Tier t) {
        return this->mp[t];
    }
};

class Map_Builder {
private:
    Map* m;
public:
    Map_Builder() {
        this->m = new Map();
    }

    ~Map_Builder() {};

    Map_Builder& set_free_tier_rate_limiter(IRate_limiter* rl) {
        this->m->mp[Tier::Free] = rl;
        return *this;
    }

    Map_Builder& set_premium_tier_rate_limiter(IRate_limiter* rl) {
        this->m->mp[Tier::Premium] = rl;
        return *this;
    }

    Map_Builder& set_deluxe_tier_rate_limiter(IRate_limiter* rl) {
        this->m->mp[Tier::Deluxe] = rl;
        return *this;
    }

    Map* build() {
        if (this->m->mp.find(Tier::Free) == this->m->mp.end()){
            cout << "set free tier rate limiter..." << endl;
            return nullptr;
        }
        if (this->m->mp.find(Tier::Premium) == this->m->mp.end()) {
            cout << "set premium tier rate limiter..." << endl;
            return nullptr;
        }
        if (this->m->mp.find(Tier::Deluxe) == this->m->mp.end()) {
            cout << "set deluxe rate limiter first..." << endl;
            return nullptr;
        }
        return this->m;
    }
};
