// ============ REQUEST / RESPONSE CLASSES ======================
class Request {
private:
    string user_id;
    map<string, string> headers;

    long long req_time; // this is generated by server at time of arrival of request on rate limiter
public:
    Request(string user_id, map<string, string>& headers) {
        this->user_id = user_id;
        this->headers = headers;

        // generate time here only
        auto wall_now = chrono::system_clock::now();
        long long time_ms = chrono::duration_cast<chrono::milliseconds>(wall_now.time_since_epoch()).count();


        this->req_time = time_ms;

    }
    ~Request() {};
    string get_user_id () {
        return this->user_id;
    }
    long long get_req_time() {
        return this->req_time;
    }
    // getter
    map<string, string>& get_headers() {
        return this->headers;
    }
};

class Response {
private:
    int status_code;
    string message;
public:
    Response(int status_code, string message) {
        this->status_code = status_code;
        this->message = message;
    }
    ~Response() {};

    // getter
    int get_status_code() {
        return this->status_code;
    }

    string get_response_message() {
        return this->message;
    }
};
