// ======================== Facade (singleton pattern) : thread safe ===================
class Facade {
private:
    static Facade* instance;
    Map* mp;
    Tier_Map* tmp;
    Facade() {
        this->tmp = new Tier_Map();
    };
    ~Facade() {
        if (this->mp!=nullptr) {
            delete this->mp;
        }
        delete this->tmp;
    };
public:
    static Facade* get_instance() {
        return Facade::instance;
    }

    // firstly backend engineer will set up the ratelimiters, that he want for respective tiers
    void set_map(Map* m) {
        this->mp = m;
    }

    // delegated functionalities(prevents facade from being a god object)
    void add_member(string user_id, Tier t) {
        this->tmp->add_member(user_id, t);
    }

    Tier get_tier(string user_id) {
        return this->tmp->get_tier(user_id);
    }

    Response* send_to_server(Request* r) {
        return this->mp->get_rate_limiter(this->get_tier(r->get_user_id()))->receive_request(r);
    }

};

Facade* Facade::instance = new Facade();
